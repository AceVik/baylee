//! The interface's own words, in every language the client speaks.
//!
//! Card text is translated by the gateway out of the catalog, field by field.
//! The *interface* — every button, caption and status line — is here: one
//! Project Fluent file per table and language under `locales/<lang>/`
//! (`interface.ftl` for [`Phrase`], `replay.ftl` for [`ReplayPhrase`],
//! `chat.ftl` for [`ChatPhrase`], `server.ftl` for [`ServerPhrase`], the
//! servers' refusals matched by their English), embedded at build time.
//!
//! # English decides, the tests hold the rest
//!
//! `build.rs` makes the enums from the English files: a message is a variant
//! named by its id, its `#` comment the variant's doc, and its
//! `# Arguments: a, b` line the order a caller passes `fill`'s arguments in.
//! Every other language only translates. A runtime table answers a missing
//! key with a fallback, and a fallback is a screen that is half German, so
//! `every_language_says_every_phrase_with_the_same_arguments` refuses the
//! build that would ship one: each file parses whole, says every English id
//! once and nothing else, and uses the same arguments as English (`$count`
//! moving is what translation *is*, `$count` vanishing is a bug). At runtime
//! a message a language lacks still reads in English rather than as an id.
//!
//! # Plurals are the language's
//!
//! A sentence whose subject is counted is one message with a selector on
//! `$count` (`{ $count -> [one] … *[other] … }`), and [`Phrase::fill_count`]
//! (or [`Phrase::text_count`], for a caller that fills the slots itself)
//! passes the number, so each language picks its own CLDR forms: English and
//! German split at one, Polish has three forms, Japanese one. **Zero takes
//! the plural** in both of ours. `card(s)` and `Karte(n)` are not plurals,
//! and **no phrase carries a bracketed plural** (a test).
//!
//! Nothing here touches a renderer, so the whole of it is testable without a
//! window. Known engine and gateway refusals are localized by
//! [`server_message`]. Unknown diagnostics keep the original detail so a
//! newer server remains diagnosable by an older client. Card and player names
//! are never translated by replacing words inside arbitrary messages.

