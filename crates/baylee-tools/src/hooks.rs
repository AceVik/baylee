//! Claude card-test bookkeeping. Hooks fail open on tooling errors, but an
//! explicitly identified committed test debt blocks Stop once per turn.
use std::{
    collections::BTreeSet,
    fs,
    io::{self, Read},
    path::{Component, Path, PathBuf},
    process::Command,
};

use anyhow::{Context, Result, bail};
use regex::Regex;
use serde_json::Value;
use syn::visit::Visit;

const CARDS: &str = "crates/baylee-cards/src/cards/";
const READERS: &str = "crates/baylee-cards-codegen/src/";
const STUB: &str = "// GENERATED STUB";
const OWNED: &str = "// IMPLEMENTED — generated by `xtask codegen`";
const FILE_FLOOR: usize = 30;
const ID_FLOOR: usize = 120;

fn safe_relative(path: &Path) -> bool {
    !path.as_os_str().is_empty() && path.components().all(|p| matches!(p, Component::Normal(_)))
}

fn record(root: &Path, event: &Value) -> Result<()> {
    if !matches!(
        event["tool_name"].as_str(),
        Some("Edit" | "Write" | "MultiEdit" | "NotebookEdit")
    ) {
        return Ok(());
    }
    let path = event["tool_input"]["file_path"]
        .as_str()
        .unwrap_or_default();
    let Some((_, rel)) = path.split_once(CARDS) else {
        return Ok(());
    };
    if Path::new(rel).extension().is_none_or(|e| e != "rs")
        || Path::new(rel).file_name().is_some_and(|n| n == "mod.rs")
        || !safe_relative(Path::new(rel))
    {
        return Ok(());
    }
    let debt = root.join(".claude/card-test-debt");
    let mut seen = fs::read_to_string(&debt)
        .unwrap_or_default()
        .lines()
        .map(str::to_owned)
        .collect::<BTreeSet<_>>();
    if seen.insert(rel.into()) {
        fs::create_dir_all(debt.parent().context("debt parent")?)?;
        fs::write(debt, seen.into_iter().collect::<Vec<_>>().join("\n") + "\n")?;
    }
    Ok(())
}

#[derive(Default)]
struct Handles(BTreeSet<String>);
impl<'ast> Visit<'ast> for Handles {
    fn visit_macro(&mut self, node: &'ast syn::Macro) {
        self.macro_tokens(node.tokens.clone());
    }

    fn visit_expr_call(&mut self, node: &'ast syn::ExprCall) {
        if let syn::Expr::Path(p) = node.func.as_ref()
            && p.path
                .segments
                .last()
                .is_some_and(|s| s.ident == "card_index")
            && let Some(syn::Expr::Lit(lit)) = node.args.first()
            && let syn::Lit::Str(id) = &lit.lit
            && uuid::Uuid::parse_str(&id.value()).is_ok()
        {
            self.0.insert(id.value());
        }
        syn::visit::visit_expr_call(self, node);
    }
}

impl Handles {
    // Macro bodies are opaque to syn's expression visitor. Token groups retain
    // real calls while excluding comments and names merely mentioned in strings.
    fn macro_tokens(&mut self, tokens: proc_macro2::TokenStream) {
        use proc_macro2::{Delimiter, TokenTree};
        use syn::parse::Parser as _;
        let mut tokens = tokens.into_iter().peekable();
        while let Some(token) = tokens.next() {
            match token {
                TokenTree::Ident(name) if name == "card_index" => {
                    if let Some(TokenTree::Group(args)) = tokens.peek()
                        && args.delimiter() == Delimiter::Parenthesis
                        && let Ok(args) = syn::punctuated::Punctuated::<syn::LitStr, syn::Token![,]>::parse_terminated.parse2(args.stream())
                        && args.len() == 1
                        && let Some(id) = args.first()
                        && uuid::Uuid::parse_str(&id.value()).is_ok()
                    { self.0.insert(id.value()); }
                }
                TokenTree::Group(group) => self.macro_tokens(group.stream()),
                _ => {}
            }
        }
    }
}

fn collect_tests(
    dir: &Path,
    in_tests: bool,
    handles: &mut Handles,
    count: &mut usize,
) -> Result<()> {
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        // Do not follow symlinks out of the engine tree.
        let ty = entry.file_type()?;
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if ty.is_dir() {
            collect_tests(&path, in_tests || name.ends_with("_tests"), handles, count)?;
        } else if ty.is_file()
            && path.extension().is_some_and(|e| e == "rs")
            && (in_tests || name.ends_with("_tests.rs"))
        {
            let source = fs::read_to_string(&path)?;
            let syntax =
                syn::parse_file(&source).with_context(|| format!("parse {}", path.display()))?;
            handles.visit_file(&syntax);
            *count += 1;
        }
    }
    Ok(())
}

fn oracle(text: &str) -> Option<String> {
    let header = Regex::new(r"(?m)^//! .*Oracle ID: ([0-9a-f-]{36})").expect("literal regex");
    let fallback = Regex::new(r#"oracle_id\s*=\s*"([0-9a-f-]{36})""#).expect("literal regex");
    header
        .captures(text)
        .or_else(|| fallback.captures(text))
        .map(|c| c[1].to_owned())
}

fn changed(root: &Path) -> Result<BTreeSet<String>> {
    let mut paths = BTreeSet::new();
    for range in ["origin/main...HEAD", "HEAD"] {
        let out = Command::new("git")
            .current_dir(root)
            .args(["diff", "--name-only", range])
            .output()?;
        if !out.status.success() {
            bail!("git could not identify the branch's changed paths");
        }
        paths.extend(
            String::from_utf8(out.stdout)?
                .lines()
                .filter(|s| !s.is_empty())
                .map(str::to_owned),
        );
    }
    Ok(paths)
}

fn check(root: &Path, event: &Value) -> Result<Option<String>> {
    if event["stop_hook_active"].as_bool() == Some(true) {
        return Ok(None);
    }
    let mut handles = Handles::default();
    let mut count = 0;
    collect_tests(
        &root.join("crates/baylee-engine/src/engine"),
        false,
        &mut handles,
        &mut count,
    )?;
    if count < FILE_FLOOR || handles.0.len() < ID_FLOOR {
        bail!(
            "require-card-tests read {count} files holding {} ids (floors {FILE_FLOOR}/{ID_FLOOR}); fix the walk, not the cards",
            handles.0.len()
        );
    }
    let debt = root.join(".claude/card-test-debt");
    let mut owed = Vec::new();
    for rel in fs::read_to_string(&debt).unwrap_or_default().lines() {
        if !safe_relative(Path::new(rel)) {
            bail!("invalid relative path in card-test debt");
        }
        let path = root.join(CARDS).join(rel);
        if !path.is_file() {
            continue;
        }
        let uncommitted = Command::new("git")
            .current_dir(root)
            .args(["diff", "--quiet", "HEAD", "--"])
            .arg(&path)
            .status()?;
        if !uncommitted.success() {
            continue;
        }
        let text = fs::read_to_string(path)?;
        if text.contains(STUB) || text.contains(OWNED) {
            continue;
        }
        if let Some(id) = oracle(&text)
            && !handles.0.contains(&id)
        {
            owed.push((rel.to_owned(), id));
        }
    }
    if owed.is_empty() && debt.exists() {
        fs::remove_file(&debt)?;
    }
    let paths = changed(root)?;
    let readers = paths
        .iter()
        .filter(|p| p.starts_with(READERS) && Path::new(p).extension().is_some_and(|e| e == "rs"))
        .collect::<Vec<_>>();
    let mut generated = Vec::new();
    if !readers.is_empty() {
        for path in paths.iter().filter(|p| {
            p.starts_with(CARDS)
                && Path::new(p).extension().is_some_and(|e| e == "rs")
                && Path::new(p).file_name().is_none_or(|n| n != "mod.rs")
        }) {
            let path_on_disk = root.join(path);
            if !path_on_disk.is_file() {
                continue;
            }
            let text = fs::read_to_string(path_on_disk)?;
            if text.contains(STUB) || !text.contains(OWNED) {
                continue;
            }
            if let Some(id) = oracle(&text) {
                generated.push((path.clone(), id));
            }
        }
        if generated.iter().any(|(_, id)| handles.0.contains(id)) {
            generated.clear();
        }
    }
    Ok(report(&owed, &readers, &generated))
}

fn report(
    owed: &[(String, String)],
    readers: &[&String],
    generated: &[(String, String)],
) -> Option<String> {
    if owed.is_empty() && generated.is_empty() {
        return None;
    }
    let mut lines = Vec::new();
    if !owed.is_empty() {
        lines.push(format!(
            "{} committed card(s) written this session are not played by an engine test:",
            owed.len()
        ));
        for (path, id) in owed.iter().take(25) {
            lines.push(format!("  {path}\n      card_index(\"{id}\")"));
        }
        if owed.len() > 25 {
            lines.push(format!(
                "  … and {} more (.claude/card-test-debt)",
                owed.len() - 25
            ));
        }
    }
    if !generated.is_empty() {
        lines.push(format!(
            "A reader changed and {} machine-owned card(s) changed with it; none is played:",
            generated.len()
        ));
        lines.extend(readers.iter().take(10).map(|p| format!("  {p}")));
        for (path, id) in generated.iter().take(25) {
            lines.push(format!("  {path}\n      card_index(\"{id}\")"));
        }
    }
    lines.push("Play the card in engine/card_tests or combo_tests on the shared testkit; never put tests in a card data file. A fix also owes a regression beside the broken rule which fails against the old code. Work still uncommitted is not asked about. Clear .claude/card-test-debt once paid, or deliberately with a recorded reason. The generated-card check needs one played output of the changed reader, not one per generated card.".into());
    Some(lines.join("\n"))
}

pub fn run(default_root: &Path, args: &[String]) -> Result<()> {
    let [mode] = args else {
        bail!("usage: hooks card-test-debt|require-card-tests");
    };
    if !matches!(mode.as_str(), "card-test-debt" | "require-card-tests") {
        bail!("unknown hook");
    }
    // A hook must not turn a bookkeeping/tooling failure into a wedged session.
    let outcome = (|| -> Result<Option<String>> {
        let mut input = String::new();
        io::stdin().take(1 << 20).read_to_string(&mut input)?;
        let event: Value = serde_json::from_str(&input)?;
        let root = std::env::var_os("CLAUDE_PROJECT_DIR")
            .map(PathBuf::from)
            .or_else(|| event["cwd"].as_str().map(PathBuf::from))
            .unwrap_or_else(|| default_root.to_owned());
        if mode == "card-test-debt" {
            record(&root, &event)?;
            Ok(None)
        } else {
            check(&root, &event)
        }
    })();
    match outcome {
        Ok(Some(report)) => {
            eprintln!("{report}");
            std::process::exit(2);
        }
        Err(error) if mode == "require-card-tests" => {
            eprintln!("require-card-tests hook failed: {error:#}");
        }
        _ => {}
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;
    #[test]
    fn debt_is_unique_and_traversal_is_not_recorded() {
        let dir = tempfile::tempdir().unwrap();
        let event = json!({"tool_name":"Write","tool_input":{"file_path":format!("/repo/{CARDS}creatures/a.rs")}});
        record(dir.path(), &event).unwrap();
        record(dir.path(), &event).unwrap();
        assert_eq!(
            fs::read_to_string(dir.path().join(".claude/card-test-debt")).unwrap(),
            "creatures/a.rs\n"
        );
        record(dir.path(), &json!({"tool_name":"Write","tool_input":{"file_path":format!("{CARDS}../../secret.rs")}})).unwrap();
        assert_eq!(
            fs::read_to_string(dir.path().join(".claude/card-test-debt"))
                .unwrap()
                .lines()
                .count(),
            1
        );
    }
    #[test]
    fn nested_card_tests_count_but_comment_mentions_do_not() {
        let dir = tempfile::tempdir().unwrap();
        let nested = dir.path().join("card_tests/creatures/goblins");
        fs::create_dir_all(&nested).unwrap();
        fs::write(
            nested.join("a.rs"),
            r#"// card_index("00000000-0000-0000-0000-000000000001")
fn test() { let _ = card_index("00000000-0000-0000-0000-000000000002"); assert_eq!(card_index("00000000-0000-0000-0000-000000000003"), other); }"#,
        )
        .unwrap();
        let mut handles = Handles::default();
        let mut count = 0;
        collect_tests(dir.path(), false, &mut handles, &mut count).unwrap();
        assert_eq!(count, 1);
        assert_eq!(handles.0.len(), 2);
        assert!(handles.0.contains("00000000-0000-0000-0000-000000000002"));
    }
    #[test]
    fn oracle_header_and_macro_are_read() {
        let id = "00000000-0000-0000-0000-000000000001";
        assert_eq!(
            oracle(&format!("//! Foo — Oracle ID: {id}")),
            Some(id.into())
        );
        assert_eq!(oracle(&format!("oracle_id = \"{id}\";")), Some(id.into()));
        assert!(!safe_relative(Path::new("../test.rs")));
    }
}
