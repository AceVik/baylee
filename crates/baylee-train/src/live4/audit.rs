//! Local decision identity; this is neither a game record nor training admission.
use crate::features4::{SourceKind4, StepProvenance4};
use anyhow::ensure;
use serde::Serialize;
use sha2::{Digest as _, Sha256};
use std::fmt::Write as _;

/// Hash-only audit of a generated action. Transport delivery is recorded separately.
/// Contains no raw view, deck, pending question, action, credentials or player name.
#[derive(Clone, Debug, Serialize)]
pub struct LiveDecision4 {
    /// Explicit local format; not an admitted rollout or converter input.
    pub schema: &'static str,
    /// One-based count of decisions generated by this adapter.
    pub decision: u64,
    /// Transport sequence of the question answered.
    pub seq: u64,
    /// One-based clock of genuinely changed authorized observations.
    pub observation: u64,
    /// SHA256 of the exact normalized policy view used for this decision.
    pub view_sha256: String,
    /// SHA256 of the observation-clock projection, excluding transport/clocks.
    pub observation_sha256: String,
    /// SHA256 of the semantic, Rust-serialized offered question.
    pub pending_sha256: String,
    /// SHA256 of the exact Rust-serialized outgoing action bytes.
    pub action_sha256: String,
    /// Hash chain of initialization, consumed observations and prior decisions.
    pub history_sha256: String,
    /// Runtime provenance for the generated action; not a training eligibility flag.
    pub provenance: StepProvenance4,
}

pub(super) fn digest(bytes: &[u8]) -> String {
    hex(&Sha256::digest(bytes))
}

pub(super) fn hex(bytes: &[u8]) -> String {
    let mut output = String::with_capacity(bytes.len() * 2);
    for byte in bytes {
        write!(&mut output, "{byte:02x}").expect("writing into String cannot fail");
    }
    output
}

pub(super) fn extend(history: &mut Sha256, tag: &[u8], bytes: &[u8]) {
    history.update((tag.len() as u64).to_le_bytes());
    history.update(tag);
    history.update((bytes.len() as u64).to_le_bytes());
    history.update(bytes);
}

pub(super) fn validate(provenance: StepProvenance4) -> anyhow::Result<()> {
    ensure!(
        provenance.temperature.is_finite()
            && provenance.temperature >= 0.0
            && provenance.thinking_steps <= 8
            && provenance.behavior_logprob.is_finite(),
        "invalid live decision provenance"
    );
    ensure!(
        !provenance.has_logprob
            || (provenance.source == SourceKind4::Net
                && provenance.temperature > 0.35
                && provenance.thinking_steps > 0
                && provenance.behavior_logprob <= 0.0),
        "live behavior probability requires a stochastic neural answer"
    );
    ensure!(
        provenance.has_logprob || provenance.behavior_logprob == 0.0,
        "live answer without behavior probability must carry zero logprob"
    );
    Ok(())
}
