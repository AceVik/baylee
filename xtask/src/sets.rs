//! `cargo xtask sets`: the release day of every set the `CardIndex` ledger
//! names, which decides the group of `crates/cards/sets` a card lies in
//! (`baylee_cards_codegen::layout`).

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::Context as _;
use baylee_cards_codegen::scryfall;

use crate::files::write_verbatim;

/// Where the table lives.
const SETS_FILE: &str = "crates/baylee-cards-index/src/sets.rs";

/// Keeps every day the table has, adds the days of the ledger's sets it
/// lacks from Scryfall's `/sets`, and writes the table sorted by code.
pub(crate) fn run(root: &Path, cache: &Path, check: bool) -> anyhow::Result<()> {
    let mut days: BTreeMap<String, String> = baylee_cards_index::SETS
        .iter()
        .map(|(code, day)| ((*code).to_owned(), (*day).to_owned()))
        .collect();
    let needed: BTreeSet<&str> = baylee_cards_index::ROWS.iter().map(|row| row.set).collect();
    let missing: Vec<&str> = needed
        .iter()
        .copied()
        .filter(|set| !days.contains_key(*set))
        .collect();
    if !missing.is_empty() {
        let listed = scryfall::fetch_sets(&ureq::Agent::new_with_defaults(), &root.join(cache))?;
        let by_code: BTreeMap<&str, Option<&str>> = listed
            .iter()
            .map(|set| (set.code.as_str(), set.released_at.as_deref()))
            .collect();
        for set in missing {
            let day = by_code
                .get(set)
                .copied()
                .flatten()
                .with_context(|| format!("Scryfall lists no release day for set {set:?}"))?;
            days.insert(set.to_owned(), day.to_owned());
        }
    }
    let mut changed: Vec<PathBuf> = Vec::new();
    write_verbatim(check, &root.join(SETS_FILE), &render(&days), &mut changed)?;
    println!("sets: {} with a release day", days.len());
    Ok(())
}

/// The table as Rust, one set per line.
fn render(days: &BTreeMap<String, String>) -> String {
    let mut out = String::from(
        "// GENERATED by `cargo xtask sets` — do not edit by hand.\n//\n\
         // The release day of every set a ledger row names, from Scryfall's `/sets`,\n\
         // sorted by code. Append-only like the ledger: a day once written is kept,\n\
         // because it decides where a card's file lies (`crates/cards/sets/<group>`).\n\n\
         #![allow(missing_docs, clippy::all, clippy::pedantic)]\n\n\
         #[rustfmt::skip]\npub static SETS: &[(&str, &str)] = &[\n",
    );
    for (code, day) in days {
        let _ = writeln!(out, "    ({code:?}, {day:?}),");
    }
    out.push_str("];\n");
    out
}

#[cfg(test)]
mod tests {
    use super::render;
    use std::collections::BTreeMap;

    /// An empty table renders as the committed placeholder did, and a day is
    /// one line in code order.
    #[test]
    fn the_table_is_one_line_a_set_in_code_order() {
        let days = BTreeMap::from([
            ("lea".to_owned(), "1993-08-05".to_owned()),
            ("10e".to_owned(), "2007-07-13".to_owned()),
        ]);
        let text = render(&days);
        let a = text.find("(\"10e\", \"2007-07-13\")").expect("10e");
        let b = text.find("(\"lea\", \"1993-08-05\")").expect("lea");
        assert!(a < b, "{text}");
        assert!(text.ends_with("];\n"));
    }
}
