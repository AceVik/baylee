//! Materialize the closed recipe catalog into static DSL objects and exact text.
//! This is source generation; no recipe is interpreted by the running engine.
use baylee_tower_relics::{Recipe, Sigil, Vessel};
use std::fmt::Write;
use std::path::{Path, PathBuf};

pub(crate) fn prepare(
    root: &Path,
    check: bool,
    registry_only: bool,
    changed: &mut Vec<PathBuf>,
) -> anyhow::Result<()> {
    if registry_only {
        return Ok(());
    }
    crate::files::write_or_check(
        check,
        &root.join("crates/cards/src/tokens/tower/run/runic/generated.rs"),
        &render(),
        changed,
    )
}

const TIERS: [(&str, &str); 4] = [
    ("COMMON", "Common"),
    ("UNCOMMON", "Uncommon"),
    ("RARE", "Rare"),
    ("MYTHIC", "Mythic Rare"),
];

fn symbol(sigil: Sigil, vessel: Vessel, tier: usize) -> String {
    format!("TOWER_RUNIC_{sigil:?}_{vessel:?}_{}", TIERS[tier].0).to_uppercase()
}

pub(crate) fn render() -> String {
    let mut out = String::from(
        "// GENERATED by cargo xtask codegen --tables; do not edit.\n//! Closed runic relic catalog; all runtime effects are ordinary static DSL.\nuse super::{TokenDef, Sigil, Vessel, charge, active_for, bonus, legend, UPKEEP_CHARGE};\n\n",
    );
    for index in 0..Recipe::COUNT {
        let Recipe { sigil, vessel } = Recipe::from_index(index).expect("closed recipe index");
        for (tier, (_, rarity)) in TIERS.iter().enumerate() {
            let name = format!("{} {} — {rarity}", sigil.title(), vessel.title());
            writeln!(out, "/// Original {name} run equipment.\npub static {}: TokenDef = TokenDef {{\n    name: {name:?},\n    abilities: &[\n        charge(Sigil::{sigil:?}, {tier}),\n        active_for(Sigil::{sigil:?}, Vessel::{vessel:?}, {tier}),", symbol(sigil, vessel, tier)).unwrap();
            if tier >= 1 {
                writeln!(out, "        UPKEEP_CHARGE,").unwrap();
            }
            if tier >= 2 {
                writeln!(out, "        bonus(Vessel::{vessel:?}),").unwrap();
            }
            if tier >= 3 {
                writeln!(out, "        legend(Vessel::{vessel:?}),").unwrap();
            }
            writeln!(out, "    ],\n    ..TokenDef::DEFAULT\n}};\n").unwrap();
        }
    }
    writeln!(out, "/// Frozen recipe/rarity order; appended after the original eighteen families.\npub const RELICS: [[&TokenDef; 4]; {}] = [", Recipe::COUNT).unwrap();
    for sigil in Sigil::ALL {
        for vessel in Vessel::ALL {
            writeln!(
                out,
                "    [{}],",
                (0..4)
                    .map(|tier| format!("&{}", symbol(sigil, vessel, tier)))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
            .unwrap();
        }
    }
    writeln!(out, "];\n\n/// Original table/LLM sentences in executable ability order.\npub const TEXTS: [[&[&str]; 4]; {}] = [", Recipe::COUNT).unwrap();
    for sigil in Sigil::ALL {
        for vessel in Vessel::ALL {
            writeln!(out, "    [").unwrap();
            for tier in 0..4 {
                let level = Recipe { sigil, vessel }.level(tier).expect("known tier");
                let mut text = vec![format!(
                    "{}, put {} charge counters on this item.",
                    sigil.event(),
                    level.gathered
                )];
                let mana = if level.mana == 0 {
                    String::new()
                } else {
                    format!("{{{}}}, ", level.mana)
                };
                let limit = match level.activations {
                    0 => String::new(),
                    1 => " Activate only once each turn.".to_owned(),
                    n => format!(" Activate only {n} times each turn."),
                };
                text.push(format!("{mana}Remove {} charge counters from this item: {}. Activate from the command zone.{limit}", level.charges, vessel.reward(level.amount)));
                if tier >= 1 {
                    text.push(
                        "At the beginning of your upkeep, put a charge counter on this item."
                            .into(),
                    );
                }
                if tier >= 2 {
                    text.push(vessel.bonus_text().into());
                }
                if tier >= 3 {
                    text.push(format!(
                        "At the beginning of your upkeep: {}.",
                        vessel.reward(level.amount)
                    ));
                }
                writeln!(out, "        &{text:?},").unwrap();
            }
            writeln!(out, "    ],").unwrap();
        }
    }
    writeln!(out, "]; ").unwrap();
    out
}
